#Los tipos de datos pueden ser: Numericos (Integer, Float, numero complejo), secuencia (String, List, tuples), diccionario, Booleano y conjunto

#Float
a = 10.0
print(type(a))

#Integer
b = 2
print(type(b))

#String
c = "Jesith"
print(type(c))

#Lista
d = [1,2,3,4]
print(type(d))

#Boolean
e = True
print(type(e))

#Tuples (similar a la lista pero los datos que tiene adentro no se puede modificar)
f = (1,"hello", 4.5, 'A')
print(type(f))

#Diccionario
g = {"a": 22, "b": 44.4}
print(type(g))

# Set (conjunto de datos)
h = {1,"hello", 4.5, 'A'}
print(type(h))
