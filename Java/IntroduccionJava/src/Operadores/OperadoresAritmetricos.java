package Operadores;

public class OperadoresAritmetricos {
    public static void main(String[] args) {
        System.out.println("*** Operadores Aritmeticos");
        int a = 5, b  = 3, resultado;

        //Suma
        resultado = a+b;
        System.out.println("Resultado = " + resultado);

        //Resta
        resultado = a-b;
        System.out.println("Resultado = " + resultado);

        // Multiplicacion
        resultado = a*b;
        System.out.println("Resultado = " + resultado);

        // Division
        resultado = a/b;
        System.out.println("resultado = " + resultado);

        // Residuo
        resultado = a % b;
        System.out.println("resultado = " + resultado);
    }
}
